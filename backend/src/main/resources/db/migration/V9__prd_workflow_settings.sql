CREATE TABLE request_message_template (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    type VARCHAR(30) NOT NULL CHECK (type IN ('ANNUAL_PLAN','MONTHLY_ACTUAL','EXPLANATION')),
    message VARCHAR(5000) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    revision BIGINT NOT NULL DEFAULT 1,
    updated_by BIGINT NOT NULL REFERENCES app_user(id),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE settings_audit_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type VARCHAR(30) NOT NULL,
    entity_id BIGINT NOT NULL,
    action VARCHAR(30) NOT NULL,
    snapshot_json TEXT NOT NULL,
    acted_by BIGINT NOT NULL REFERENCES app_user(id),
    acted_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- 제출 반려와 같은 트랜잭션에서 검증한 항목·원천·금액을 불변 스냅샷으로 보존한다.
CREATE TABLE submission_rejection_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id BIGINT NOT NULL REFERENCES submission(id),
    review_item_id BIGINT REFERENCES review_item(id),
    ordinal INTEGER NOT NULL CHECK (ordinal > 0),
    snapshot_json TEXT NOT NULL,
    rejected_by BIGINT NOT NULL REFERENCES app_user(id),
    rejected_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (submission_id, ordinal)
);
