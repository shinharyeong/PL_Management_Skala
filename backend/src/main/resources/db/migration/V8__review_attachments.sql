-- 소명 회차에 연결한 첨부 원문은 덮어쓰지 않으며 새 첨부만 추가한다.
ALTER TABLE review_explanation ADD COLUMN attachment_revision BIGINT NOT NULL DEFAULT 0;
CREATE TABLE review_attachment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    explanation_id BIGINT NOT NULL REFERENCES review_explanation(id),
    original_filename VARCHAR(255) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    byte_size BIGINT NOT NULL CHECK (byte_size BETWEEN 1 AND 16777216),
    sha256 CHAR(64) NOT NULL,
    object_key VARCHAR(100) NOT NULL UNIQUE REFERENCES stored_object(object_key),
    uploaded_by BIGINT NOT NULL REFERENCES app_user(id),
    uploaded_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_review_attachment_round ON review_attachment(explanation_id,id);
