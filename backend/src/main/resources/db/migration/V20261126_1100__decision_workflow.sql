-- 기존 제출·소명 알림과 분리된 의사결정 개선 요청함. 실제 메일 전송 작업은 만들지 않는다.
CREATE TABLE decision_work_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_id BIGINT NOT NULL REFERENCES decision_agent_analysis(id),
    owner_id BIGINT NOT NULL REFERENCES app_user(id),
    organization_id BIGINT NOT NULL REFERENCES organization(id),
    candidate_id VARCHAR(100) NOT NULL,
    hypothesis_id VARCHAR(100),
    revision INTEGER NOT NULL CHECK (revision > 0),
    state_code VARCHAR(30) NOT NULL CHECK (state_code IN (
        'DRAFT','REQUESTED','REPLIED','CHANGES_REQUESTED','ACCEPTED','REJECTED',
        'APPROVED','DECLINED','IN_PROGRESS','COMPLETED','CANCELLED')),
    body JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT decision_work_item_identity_check CHECK (
        body->>'id'=id::text AND body->>'analysisId'=analysis_id::text
        AND body->>'ownerId'=owner_id::text AND body->>'organizationId'=organization_id::text
        AND body->>'candidateId'=candidate_id),
    CONSTRAINT decision_work_item_version_check CHECK (
        (body->>'revision')::integer=revision AND body->>'state'=state_code)
);
CREATE INDEX ix_decision_work_item_owner ON decision_work_item(owner_id,updated_at DESC,id DESC);
CREATE INDEX ix_decision_work_item_org ON decision_work_item(organization_id,updated_at DESC,id DESC);
CREATE UNIQUE INDEX ux_decision_work_item_active_candidate ON decision_work_item(analysis_id,candidate_id)
    WHERE state_code NOT IN ('REJECTED','DECLINED','COMPLETED','CANCELLED');
CREATE UNIQUE INDEX ux_decision_work_item_active_hypothesis ON decision_work_item(analysis_id,hypothesis_id)
    WHERE hypothesis_id IS NOT NULL AND state_code NOT IN ('REJECTED','DECLINED','COMPLETED','CANCELLED');

-- 목적: 요청 원본과 기존 이력 덮어쓰기를 차단한다.
-- Args: NEW/OLD 요청 행. Returns: 허용된 NEW. Raises: 기준/이력 변경 예외. Side Effects: 허용하지 않는 DB 갱신 중단.
CREATE FUNCTION guard_decision_work_item() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.analysis_id IS DISTINCT FROM OLD.analysis_id OR NEW.owner_id IS DISTINCT FROM OLD.owner_id
       OR NEW.organization_id IS DISTINCT FROM OLD.organization_id OR NEW.candidate_id IS DISTINCT FROM OLD.candidate_id
       OR NEW.hypothesis_id IS DISTINCT FROM OLD.hypothesis_id OR NEW.created_at IS DISTINCT FROM OLD.created_at
       OR (NEW.body - ARRAY['revision','state','round','updatedAt','reply','review','decision','progress','events'])
            IS DISTINCT FROM (OLD.body - ARRAY['revision','state','round','updatedAt','reply','review','decision','progress','events']) THEN
        RAISE EXCEPTION 'decision workflow source is immutable';
    END IF;
    IF NEW.revision <> OLD.revision + 1
       OR jsonb_array_length(NEW.body->'events') <> jsonb_array_length(OLD.body->'events') + 1
       OR ((NEW.body->'events') - (jsonb_array_length(NEW.body->'events') - 1)) IS DISTINCT FROM OLD.body->'events' THEN
        RAISE EXCEPTION 'decision workflow events are append only';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER decision_work_item_immutable BEFORE UPDATE ON decision_work_item
FOR EACH ROW EXECUTE FUNCTION guard_decision_work_item();
