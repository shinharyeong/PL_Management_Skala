ALTER TABLE request_target ADD COLUMN excluded BOOLEAN NOT NULL DEFAULT FALSE;

-- 마스터는 승인된 전체 제출본의 조합이다. 금액은 복제하지 않고 기존 불변 적재값을 참조한다.
CREATE TABLE annual_master (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES submission_request(id),
    seq INTEGER NOT NULL CHECK (seq > 0),
    previous_master_id BIGINT REFERENCES annual_master(id),
    trigger_submission_id BIGINT NOT NULL REFERENCES submission(id),
    content_sha256 CHAR(64) NOT NULL,
    calculation_version VARCHAR(80) NOT NULL,
    created_by BIGINT NOT NULL REFERENCES app_user(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (request_id, seq)
);

CREATE TABLE annual_master_source (
    master_id BIGINT NOT NULL REFERENCES annual_master(id),
    organization_id BIGINT NOT NULL REFERENCES organization(id),
    submission_id BIGINT NOT NULL REFERENCES submission(id),
    PRIMARY KEY (master_id, organization_id),
    UNIQUE (master_id, submission_id)
);

CREATE INDEX ix_annual_master_source_submission ON annual_master_source(submission_id);
