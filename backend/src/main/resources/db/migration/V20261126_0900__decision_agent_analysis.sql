-- 분석 생성 시 확정 기준을 복사하고 이후 후보·계산·설명 상태만 revision과 함께 변경한다.
CREATE TABLE decision_agent_analysis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES app_user(id),
    master_id BIGINT NOT NULL REFERENCES master_version(id),
    revision INTEGER NOT NULL CHECK (revision > 0),
    title VARCHAR(200) NOT NULL,
    snapshot JSONB NOT NULL,
    state JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT decision_agent_snapshot_master_check CHECK (snapshot->>'masterId'=master_id::text),
    CONSTRAINT decision_agent_state_snapshot_check CHECK (state->'snapshot'=snapshot),
    CONSTRAINT decision_agent_state_revision_check CHECK ((state->>'revision')::integer=revision)
);
CREATE INDEX ix_decision_agent_analysis_owner ON decision_agent_analysis(owner_id, updated_at DESC, id DESC);

-- 운영 경로에서도 기준 버전·소유자·snapshot 덮어쓰기를 차단한다.
CREATE FUNCTION guard_decision_agent_baseline() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.master_id IS DISTINCT FROM OLD.master_id OR NEW.owner_id IS DISTINCT FROM OLD.owner_id
       OR NEW.snapshot IS DISTINCT FROM OLD.snapshot OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'decision agent baseline is immutable';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER decision_agent_baseline_immutable BEFORE UPDATE ON decision_agent_analysis
FOR EACH ROW EXECUTE FUNCTION guard_decision_agent_baseline();
