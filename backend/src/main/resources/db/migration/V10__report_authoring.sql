CREATE TABLE report_metric (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    base_metric_code VARCHAR(20) NOT NULL CHECK (base_metric_code IN ('REVENUE','COST','OP')),
    sql_text VARCHAR(4000) NOT NULL,
    created_by BIGINT NOT NULL REFERENCES app_user(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE report_template (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    current_revision INTEGER NOT NULL CHECK (current_revision > 0),
    created_by BIGINT NOT NULL REFERENCES app_user(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE report_template_version (
    template_id BIGINT NOT NULL REFERENCES report_template(id),
    revision INTEGER NOT NULL CHECK (revision > 0),
    name VARCHAR(200) NOT NULL,
    blocks_json TEXT NOT NULL,
    created_by BIGINT NOT NULL REFERENCES app_user(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (template_id, revision)
);
CREATE TABLE report_reason_version (
    version INTEGER PRIMARY KEY CHECK (version > 0),
    items_json TEXT NOT NULL,
    created_by BIGINT NOT NULL REFERENCES app_user(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE report_material (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    current_revision INTEGER NOT NULL CHECK (current_revision > 0),
    created_by BIGINT NOT NULL REFERENCES app_user(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE report_material_version (
    material_id BIGINT NOT NULL REFERENCES report_material(id),
    revision INTEGER NOT NULL CHECK (revision > 0),
    name VARCHAR(200) NOT NULL,
    base_year INTEGER NOT NULL CHECK (base_year BETWEEN 2000 AND 9999),
    base_month INTEGER NOT NULL CHECK (base_month BETWEEN 1 AND 12),
    template_id BIGINT REFERENCES report_template(id),
    template_revision INTEGER,
    reason_version INTEGER REFERENCES report_reason_version(version),
    blocks_json TEXT NOT NULL,
    results_json TEXT NOT NULL,
    action VARCHAR(20) NOT NULL CHECK (action IN ('CREATE','APPLY','UNDO')),
    restored_revision INTEGER,
    created_by BIGINT NOT NULL REFERENCES app_user(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (material_id, revision)
);
CREATE TABLE report_authoring_proposal (
    id VARCHAR(36) PRIMARY KEY,
    material_id BIGINT NOT NULL REFERENCES report_material(id),
    expected_revision INTEGER NOT NULL,
    definition_json TEXT NOT NULL,
    results_json TEXT NOT NULL,
    reason_version INTEGER REFERENCES report_reason_version(version),
    actor_id BIGINT NOT NULL REFERENCES app_user(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    applied_revision INTEGER,
    FOREIGN KEY (material_id, applied_revision) REFERENCES report_material_version(material_id, revision)
);
CREATE INDEX ix_report_proposal_material ON report_authoring_proposal(material_id, actor_id);
