-- 업무 ERD의 제출 접수 범위만 구현한다. 승인·금융값·마스터 테이블은 후속 마이그레이션 대상이다.
CREATE TABLE organization (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(80) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(320) NOT NULL UNIQUE,
    name VARCHAR(200) NOT NULL,
    role VARCHAR(30) NOT NULL CHECK (role IN ('PLANNER', 'ORG_MANAGER')),
    organization_id BIGINT REFERENCES organization(id),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CHECK ((role = 'PLANNER' AND organization_id IS NULL)
        OR (role = 'ORG_MANAGER' AND organization_id IS NOT NULL))
);
CREATE TABLE annual_plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    year INTEGER NOT NULL UNIQUE CHECK (year BETWEEN 2000 AND 9999),
    status VARCHAR(20) NOT NULL CHECK (status IN ('COLLECTING', 'CONFIRMED')),
    contingency_amount NUMERIC(30, 6),
    confirmed_by BIGINT REFERENCES app_user(id),
    confirmed_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE submission_request (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    annual_plan_id BIGINT NOT NULL REFERENCES annual_plan(id),
    type VARCHAR(30) NOT NULL CHECK (type IN ('ANNUAL_PLAN', 'MONTHLY_ACTUAL')),
    month INTEGER CHECK (month BETWEEN 1 AND 12),
    status VARCHAR(10) NOT NULL CHECK (status IN ('OPEN', 'CLOSED')),
    message TEXT,
    due_at TIMESTAMP WITH TIME ZONE,
    requested_by BIGINT NOT NULL REFERENCES app_user(id),
    requested_at TIMESTAMP WITH TIME ZONE NOT NULL,
    -- null 월의 연간 요청도 중복을 막는 물리 키이며 API에는 노출하지 않는다.
    period_key VARCHAR(30) NOT NULL UNIQUE,
    CHECK ((type = 'ANNUAL_PLAN' AND month IS NULL) OR (type = 'MONTHLY_ACTUAL' AND month IS NOT NULL))
);
CREATE TABLE request_target (
    request_id BIGINT NOT NULL REFERENCES submission_request(id),
    organization_id BIGINT NOT NULL REFERENCES organization(id),
    confirmed_plan_submission_id BIGINT,
    PRIMARY KEY (request_id, organization_id)
);
-- 초기 저장 어댑터: 원본과 파서 JSON을 같은 DB 트랜잭션으로 보존한다. 외부 객체 저장소로 교체 가능하다.
CREATE TABLE stored_object (
    object_key VARCHAR(100) PRIMARY KEY,
    content_type VARCHAR(100) NOT NULL,
    payload BYTEA NOT NULL
);
CREATE TABLE submission (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    seq INTEGER,
    status VARCHAR(20) NOT NULL CHECK (status IN ('DRAFT', 'PENDING', 'REJECTED', 'APPROVED')),
    original_filename VARCHAR(255) NOT NULL,
    source_object_key VARCHAR(100) NOT NULL REFERENCES stored_object(object_key),
    source_sha256 CHAR(64) NOT NULL,
    uploaded_by BIGINT NOT NULL REFERENCES app_user(id),
    uploaded_at TIMESTAMP WITH TIME ZONE NOT NULL,
    submitted_by BIGINT REFERENCES app_user(id),
    submitted_at TIMESTAMP WITH TIME ZONE,
    reviewed_by BIGINT REFERENCES app_user(id),
    reviewed_at TIMESTAMP WITH TIME ZONE,
    reject_reason TEXT,
    FOREIGN KEY (request_id, organization_id) REFERENCES request_target(request_id, organization_id),
    UNIQUE (request_id, organization_id, seq),
    CHECK ((status = 'DRAFT' AND seq IS NULL) OR (status <> 'DRAFT' AND seq IS NOT NULL AND seq > 0))
);
ALTER TABLE request_target ADD CONSTRAINT fk_confirmed_plan_source
    FOREIGN KEY (confirmed_plan_submission_id) REFERENCES submission(id);
CREATE TABLE parsing_job (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id BIGINT NOT NULL UNIQUE REFERENCES submission(id),
    status VARCHAR(20) NOT NULL CHECK (status IN ('QUEUED', 'RUNNING', 'NEEDS_REVIEW', 'SUCCEEDED', 'FAILED')),
    engine VARCHAR(80) NOT NULL,
    parser_version VARCHAR(80),
    contract_version VARCHAR(80),
    mapping_version VARCHAR(80),
    attempt_no INTEGER NOT NULL CHECK (attempt_no > 0),
    result_object_key VARCHAR(100) REFERENCES stored_object(object_key),
    error_code VARCHAR(100),
    error_message TEXT,
    started_at TIMESTAMP WITH TIME ZONE,
    finished_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_job_queue ON parsing_job(status, id);
CREATE INDEX ix_submission_org_time ON submission(organization_id, uploaded_at, id);
-- 업무 테이블과 성공 응답을 원자적으로 기록하는 기술 테이블이다.
CREATE TABLE idempotency_record (
    actor_id BIGINT NOT NULL REFERENCES app_user(id),
    route VARCHAR(200) NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    fingerprint CHAR(64) NOT NULL,
    response_status INTEGER NOT NULL,
    response_body TEXT NOT NULL,
    location VARCHAR(200) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (actor_id, route, idempotency_key)
);
