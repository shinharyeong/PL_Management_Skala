-- 알림은 제출·소명·마감 사실에서 조회하고 사용자별 읽음만 저장한다.
CREATE TABLE notification_read (
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    event_id VARCHAR(180) NOT NULL,
    read_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (user_id, event_id)
);

-- 등록한 양식의 바이트는 수정하지 않고 새 이력을 추가한다.
CREATE TABLE request_template (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES submission_request(id),
    object_key VARCHAR(100) NOT NULL REFERENCES stored_object(object_key),
    filename VARCHAR(255) NOT NULL,
    source_sha256 CHAR(64) NOT NULL,
    registered_by BIGINT NOT NULL REFERENCES app_user(id),
    registered_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_request_template_latest ON request_template(request_id, id DESC);
