-- 과거 검증의 필수 소명 정책을 유지하고 새 PRD 정책과 검토 업무 상태를 구분한다.
ALTER TABLE gap_threshold ADD COLUMN percent_enabled BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE gap_threshold ADD COLUMN amount_enabled BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE gap_threshold ADD CONSTRAINT ck_gap_threshold_enabled CHECK (percent_enabled OR amount_enabled);
ALTER TABLE review_item ADD COLUMN review_policy_version VARCHAR(80) NOT NULL DEFAULT 'legacy/1.0';
ALTER TABLE review_item ADD COLUMN workflow_state VARCHAR(30) NOT NULL DEFAULT 'NEEDS_REVIEW'
    CHECK (workflow_state IN ('NEEDS_REVIEW','SELECTED','REQUESTED','EXCLUDED'));
ALTER TABLE review_item ADD COLUMN workflow_note VARCHAR(4000);
ALTER TABLE review_explanation ADD COLUMN due_at TIMESTAMP WITH TIME ZONE;

CREATE TABLE review_workflow_event (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_item_id BIGINT NOT NULL REFERENCES review_item(id),
    action VARCHAR(30) NOT NULL CHECK (action IN ('SELECT','EXCLUDE','REQUEST_EXPLANATION')),
    explanation_round INTEGER NOT NULL,
    note VARCHAR(4000),
    due_at TIMESTAMP WITH TIME ZONE,
    acted_by BIGINT NOT NULL REFERENCES app_user(id),
    acted_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_review_workflow_event ON review_workflow_event(review_item_id,id);

