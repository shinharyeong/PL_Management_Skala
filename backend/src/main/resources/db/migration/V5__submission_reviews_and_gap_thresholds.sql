-- 기준은 새 이력으로만 추가하며 제출 당시 비교는 해당 행을 참조한다.
CREATE TABLE gap_threshold (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scenario VARCHAR(20) NOT NULL CHECK (scenario IN ('ACTUAL','ESTIMATE')),
    percent NUMERIC(30,6) NOT NULL CHECK (percent >= 0),
    amount NUMERIC(30,6) NOT NULL CHECK (amount >= 0),
    applied_by BIGINT NOT NULL REFERENCES app_user(id),
    applied_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE review_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id BIGINT NOT NULL REFERENCES submission(id),
    report_item_id BIGINT NOT NULL REFERENCES report_item(id),
    year INTEGER NOT NULL,
    month INTEGER NOT NULL CHECK (month BETWEEN 1 AND 12),
    scenario VARCHAR(20) NOT NULL CHECK (scenario IN ('PLAN','ACTUAL','ESTIMATE')),
    amount_present BOOLEAN NOT NULL,
    current_amount NUMERIC(48,6),
    change_detected BOOLEAN NOT NULL,
    gap_exceeded BOOLEAN NOT NULL,
    source_fingerprint CHAR(64) NOT NULL,
    context_fingerprint CHAR(64) NOT NULL,
    current_round INTEGER NOT NULL CHECK (current_round > 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (submission_id,report_item_id,year,month,scenario),
    CHECK ((amount_present AND current_amount IS NOT NULL) OR (NOT amount_present AND current_amount IS NULL))
);
CREATE TABLE gap_comparison (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_item_id BIGINT NOT NULL REFERENCES review_item(id),
    basis VARCHAR(20) NOT NULL CHECK (basis IN ('PLAN','PREVIOUS')),
    baseline_submission_id BIGINT NOT NULL REFERENCES submission(id),
    baseline_scenario VARCHAR(20) NOT NULL CHECK (baseline_scenario IN ('PLAN','ACTUAL','ESTIMATE')),
    baseline_amount NUMERIC(48,6) NOT NULL,
    current_amount NUMERIC(48,6) NOT NULL,
    gap_amount NUMERIC(49,6) NOT NULL,
    gap_rate NUMERIC(60,8),
    threshold_id BIGINT NOT NULL REFERENCES gap_threshold(id),
    exceeded BOOLEAN NOT NULL,
    UNIQUE (review_item_id,basis)
);
CREATE TABLE review_explanation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_item_id BIGINT NOT NULL REFERENCES review_item(id),
    round INTEGER NOT NULL CHECK (round > 0),
    request_note VARCHAR(4000),
    requested_by BIGINT REFERENCES app_user(id),
    requested_at TIMESTAMP WITH TIME ZONE,
    answer VARCHAR(4000),
    answered_by BIGINT REFERENCES app_user(id),
    answered_at TIMESTAMP WITH TIME ZONE,
    verdict VARCHAR(20) NOT NULL CHECK (verdict IN ('PENDING','ACCEPTED','REJECTED')),
    reviewed_by BIGINT REFERENCES app_user(id),
    reviewed_at TIMESTAMP WITH TIME ZONE,
    review_note VARCHAR(4000),
    inherited_from_id BIGINT REFERENCES review_explanation(id),
    UNIQUE (review_item_id,round)
);
CREATE INDEX ix_review_submission_active ON review_item(submission_id,active);
CREATE INDEX ix_threshold_latest ON gap_threshold(scenario,id DESC);

