-- 기존 원본·초안·파서 결과를 보존하고 검증 완료한 월별 상세와 검증 근거만 추가한다.
ALTER TABLE submission ADD COLUMN previous_submission_id BIGINT REFERENCES submission(id);

CREATE TABLE account_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_type VARCHAR(30) NOT NULL CHECK (source_type IN ('REVENUE_CLASS', 'EXPENSE_BUDGET')),
    source_code VARCHAR(160) NOT NULL,
    source_name VARCHAR(500) NOT NULL,
    UNIQUE (source_type, source_code, source_name)
);

CREATE TABLE report_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(160) NOT NULL UNIQUE,
    name VARCHAR(500) NOT NULL,
    parent_id BIGINT REFERENCES report_item(id),
    kind VARCHAR(20) NOT NULL CHECK (kind IN ('REVENUE', 'COST', 'DERIVED')),
    is_leaf BOOLEAN NOT NULL,
    calculation_code VARCHAR(80),
    display_order INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE financial_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id BIGINT NOT NULL REFERENCES submission(id),
    account_item_id BIGINT REFERENCES account_item(id),
    report_item_id BIGINT NOT NULL REFERENCES report_item(id),
    detail_id VARCHAR(500),
    detail_revision VARCHAR(80),
    headquarters_code VARCHAR(160),
    team_code VARCHAR(160),
    task_code VARCHAR(160),
    management_category VARCHAR(500),
    actual_basis VARCHAR(500),
    cost_type VARCHAR(500),
    description TEXT,
    source_sheet VARCHAR(255) NOT NULL,
    source_row INTEGER NOT NULL CHECK (source_row > 0),
    UNIQUE (submission_id, source_sheet, source_row)
);

CREATE TABLE financial_value (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    line_id BIGINT NOT NULL REFERENCES financial_line(id),
    year INTEGER NOT NULL CHECK (year BETWEEN 2000 AND 9999),
    month INTEGER NOT NULL CHECK (month BETWEEN 1 AND 12),
    scenario VARCHAR(20) NOT NULL CHECK (scenario IN ('PLAN', 'ACTUAL', 'ESTIMATE')),
    amount NUMERIC(30, 6) NOT NULL,
    source_record_id VARCHAR(500) NOT NULL,
    source_cell VARCHAR(30) NOT NULL,
    UNIQUE (line_id, year, month, scenario)
);

-- 파서 결과 자체와 업무 검증 결과는 별도 불변 객체로 보관한다. 현재 초안이 채택한 검증만 참조한다.
CREATE TABLE submission_validation (
    submission_id BIGINT PRIMARY KEY REFERENCES submission(id),
    attempt_no INTEGER NOT NULL CHECK (attempt_no > 0),
    source_sha256 CHAR(64) NOT NULL,
    parser_result_object_key VARCHAR(100) NOT NULL REFERENCES stored_object(object_key),
    policy_version VARCHAR(80) NOT NULL,
    validation_result_object_key VARCHAR(100) NOT NULL REFERENCES stored_object(object_key),
    validated_by BIGINT NOT NULL REFERENCES app_user(id),
    validated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_financial_line_report ON financial_line(submission_id, report_item_id, id);
CREATE INDEX ix_financial_value_period ON financial_value(year, month, scenario, line_id);
